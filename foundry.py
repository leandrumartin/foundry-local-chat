from collections.abc import Generator

from foundry_local_sdk import (
    ChatSession,
    Configuration,
    FoundryLocalManager,
    MessageItem,
    MessageRole,
    Request,
    RequestOptions,
    TextItem,
    ToolCallItem,
    ToolChoice,
    ToolResultItem,
    TextItemType,
)
from foundry_local_sdk.imodel import IModel

role_map = {
    "none": MessageRole.NONE,
    "system": MessageRole.SYSTEM,
    "user": MessageRole.USER,
    "assistant": MessageRole.ASSISTANT,
    "tool": MessageRole.TOOL,
    "developer": MessageRole.DEVELOPER,
}

tool_choice_map = {
    "auto": ToolChoice.AUTO,
    "required": ToolChoice.REQUIRED,
    "none": ToolChoice.NONE,
}

class FoundryManager:
    def __init__(self):
        self._current_model_name: str|None = None
        self._active_models: dict[str, IModel] = {}
        self._active_model_names: dict[str, str] = {}
        self._sessions: dict[str, ChatSession] = {}
        self._session_settings: dict[str, dict] = {}
        self._manager: FoundryLocalManager = self._get_initialized_manager()
        self.loaded_model_names: list[str] = []

    def _get_initialized_manager(self) -> FoundryLocalManager:
        """Initialize the FoundryLocalManager with the application configuration. Load all execution providers, print
        the progress, and return the initialized manager.
        """

        config: Configuration = Configuration(app_name="foundry_local_chat")
        FoundryLocalManager.initialize(config)
        manager: FoundryLocalManager = FoundryLocalManager.instance

        # Download and register all execution providers.
        current_ep = ""

        def ep_progress(ep_name: str, percent: float):
            nonlocal current_ep
            if ep_name != current_ep:
                if current_ep:
                    print()
                current_ep = ep_name
            print(f"\r  {ep_name:<30}  {percent:5.1f}%", end="", flush=True)

        manager.download_and_register_eps(progress_callback=ep_progress)
        if current_ep:
            print()

        return manager

    def get_loaded_model(self, model_name: str) -> (IModel):
        """Get a model from the catalog, downloads it if necessary, and loads it into memory. Return the loaded model
        instance.
        
        Raises:
            ValueError: If the model is not found in the catalog.
        """

        model: IModel|None = self._manager.catalog.get_model(model_name)
        if model is None:
            model: IModel|None = self._manager.catalog.get_model_variant(model_name)
        if model is None:
            raise ValueError(f"Model '{model_name}' not found in the catalog.")

        model.download(
            lambda progress: print(
                f"\rDownloading model: {progress:.2f}%", end="", flush=True
            )
        )
        print()
        model.load()
        print(f"Model '{model_name}' loaded and ready.")

        return model

    def load_model(self, model_name: str, session_hash: str, retain: bool = False) -> None:
        """Load a model into memory. If retain is False, unloads all other models except the one being loaded.  """

        if not retain:
            self.unload_all_models(exceptions=[model_name])

        self._current_model_name = model_name
        if model_name not in self.loaded_model_names:
            self.loaded_model_names.append(model_name)
        previous_model_name = self._active_model_names.get(session_hash)
        self._active_models[session_hash] = self.get_loaded_model(model_name)
        self._active_model_names[session_hash] = model_name
        self._sessions[session_hash] = ChatSession(self._active_models[session_hash])
        self.restore_settings(session_hash)

        # Ensure previous model for this session is unloaded if it was different from the current one and not being used by any other session
        if not retain and previous_model_name and previous_model_name != model_name and previous_model_name not in self._active_model_names.values():
            self.unload_model(previous_model_name)

    def get_model_response(self, history: list[dict], session_hash: str, tool_results: list[dict] | None = None) -> Generator[dict]:
        """Get a response from the currently loaded model based on user input and conversation history.
        
        Raises:
            ValueError: If no model is currently loaded.

        :returns a generator that yields response tokens as they are generated by the model. The generator yields dictionaries with the following structure:
            {
                "type": "text" | "tool_call",
                "content": str | (str, str, dict)
            }
        """

        if self._sessions[session_hash] is None:
            raise ValueError("No model is currently loaded. Please load a model first.")

        if session_hash in self._session_settings and "available_tools" in self._session_settings[session_hash] and len(self._session_settings[session_hash]["available_tools"]) == 0:
            self._sessions[session_hash].set_options(RequestOptions(tool_choice=ToolChoice.AUTO))

        history = self._cleaned_history(history)

        # Stream the response token by token
        self._sessions[session_hash].set_streaming(True)

        with Request() as request:
            for message in history:
                request.add_item(
                    MessageItem(
                        role=role_map.get(message["role"], MessageRole.NONE),
                        content=message["content"]
                    )
                )

            if tool_results is not None:
                for tool_result in tool_results:
                    try:
                        request.add_item(
                            ToolResultItem(
                                call_id=tool_result["tool_call_id"],
                                result=tool_result["content"]
                            )
                        )
                    except KeyError:
                        try:
                            # Expected keys are missing in the tool_result dictionary. It might be formatted as a message.
                            #  Try rendering it as a message instead.
                            request.add_item(
                                MessageItem(
                                role=role_map.get(tool_result.get("role", "none"), MessageRole.NONE),
                                content=tool_result.get("content", "")
                                )
                            )
                        except KeyError as e:
                            raise ValueError(f"Invalid tool_result format: {tool_result}. Missing key: {e}")

            tool_calls = []
            for item in self._sessions[session_hash].process_streaming_request(request):
                if isinstance(item, TextItem):
                    if item.type == TextItemType.DEFAULT:
                        yield {"type": "text", "content": item.text}
                    elif item.type == TextItemType.REASONING:
                        yield {"type": "reasoning", "content": item.text}
                elif isinstance(item, ToolCallItem):
                    tool_calls.append((item.call_id, item.name, item.arguments))

            if len(tool_calls) > 0:
                # If the tool choice is set to REQUIRED, temporarily set it to AUTO before yielding. This allows the models
                #  to a response on the next go-around, once it has received the tool result, without requiring a tool call.
                #  This prevents the model from being stuck in an infinite loop of tool calls.
                if self._session_settings[session_hash]["tool_choice"] == ToolChoice.REQUIRED:
                    self._sessions[session_hash].set_options(RequestOptions(tool_choice=ToolChoice.AUTO))

                yield {"type": "tool_call_list", "content": tool_calls}

    def unload_model(self, model_name: str) -> None:
        """Unload a model from memory. If the model is not loaded, does nothing."""

        if model_name in self.loaded_model_names:
            model = self._manager.catalog.get_model(model_name)
            if model is None:
                model = self._manager.catalog.get_model_variant(model_name)
            if model is not None:
                model.unload()
            self.loaded_model_names.remove(model_name)
            print(f"Model '{model_name}' unloaded.")

    def unload_all_models(self, exceptions: list[str]|None = None) -> None:
        """Unload all models from memory, except those being used by active sessions and those specified in the exceptions list."""

        unloaded_model_names = []
        for model_name in self.loaded_model_names:
            if (exceptions is not None and model_name in exceptions) or model_name in self._active_model_names.values():
                continue
            self.unload_model(model_name)
            unloaded_model_names.append(model_name)
        for model_name in unloaded_model_names:
            if model_name in self.loaded_model_names:
                self.loaded_model_names.remove(model_name)

    def _cleaned_history(self, history: list[dict]) -> list[dict[str, str]]:
        """Clean the conversation history by replacing the 'content' fields containing dictionaries with their 'text'
        values. This ensures that the history is in the correct format for the model to process."""

        cleaned_history = []
        for entry in history:
            if isinstance(entry.get("content"), str):
                cleaned_entry = entry
            else:
                # Other possible format is list[dict], i.e. [{"type": "text", "text": "some text"}]
                text_content = entry["content"][0].get("text", "")
                cleaned_entry = {
                    "role": entry.get("role", ""),
                    "content": text_content
                }
            cleaned_history.append(cleaned_entry)

        return cleaned_history

    def load_new_session(self, session_hash: str) -> None:
        """Create a new chat session for the currently loaded model. Raises an error if no model is loaded."""
        if session_hash not in self._active_models:
            raise ValueError("No model is currently loaded. Please load a model first.")
        self._sessions[session_hash] = ChatSession(self._active_models[session_hash])
        self.restore_settings(session_hash)

    def restore_settings(self, session_hash: str):
        """Restore available settings for the given session hash. If no settings exist, defaults are used."""
        self.update_tool_choice(session_hash,
                                self._session_settings.get(session_hash, {}).get("tool_choice", ToolChoice.AUTO))
        self.update_available_tools(session_hash,
                                    self._session_settings.get(session_hash, {}).get("available_tools", []))

    def unload_session(self, session_hash: str) -> None:
        """Unload the chat session for the given session hash. Does not unload the model itself."""
        if session_hash in self._sessions:
            del self._sessions[session_hash]
            del self._active_models[session_hash]
            del self._active_model_names[session_hash]
        if session_hash in self._session_settings:
            del self._session_settings[session_hash]

    def get_active_model(self, session_hash: str) -> IModel|None:
        """Get the name of the currently active model for the given session hash. Returns None if no model is active."""
        return self._active_models.get(session_hash)

    def update_tool_choice(self, session_hash: str, tool_choice: str | ToolChoice) -> None:
        """Update the tool choice setting for the given session hash."""
        if isinstance(tool_choice, ToolChoice):
            mapped_tool_choice = tool_choice
        else:
            mapped_tool_choice = tool_choice_map.get(tool_choice, ToolChoice.AUTO)

        if session_hash in self._session_settings:
            self._session_settings[session_hash]["tool_choice"] = mapped_tool_choice
        else:
            self._session_settings[session_hash] = {"tool_choice": mapped_tool_choice}

        if session_hash in self._sessions:
            self._sessions[session_hash].set_options(RequestOptions(tool_choice=mapped_tool_choice))

    def update_available_tools(self, session_hash: str, available_tools: list[dict]) -> None:
        """Update the available tools for the given session hash."""
        if session_hash in self._sessions:
            if session_hash in self._session_settings:
                if "available_tools" in self._session_settings[session_hash]:
                    for tool in self._session_settings[session_hash]["available_tools"]:
                        if tool["name"] not in [t["name"] for t in available_tools]:
                            # Remove any tools previously available that are no longer in the new list of available tools
                            try:
                                self._sessions[session_hash].remove_tool_definition(tool["name"])
                            except Exception as e:
                                print(f"Error removing tool definition for {tool['name']}: {e}")
                for tool in available_tools:
                    # Add newly available tools
                    try:
                        self._sessions[session_hash].add_tool_definition(
                            tool["name"],
                            tool["description"],
                            tool["parameters"]
                        )
                    except Exception as e:
                        print(f"Error adding tool definition for {tool['name']}: {e}")
            else:
                # If no previous session settings exist, just add the new tools
                for tool in available_tools:
                    try:
                        self._sessions[session_hash].add_tool_definition(
                            tool["name"],
                            tool["description"],
                            tool["parameters"]
                        )
                    except Exception as e:
                        print(f"Error adding tool definition for {tool['name']}: {e}")

            self._session_settings[session_hash]["available_tools"] = available_tools